async function loadUserAndLimits(uid) {
  if (!db) throw new Error('database_unavailable');
  const [userSnap, usageSnap] = await Promise.all([
    db.collection('users').doc(uid).get(),
    db.collection('usage').doc(uid).get(),
  ]);
  const user = userSnap.exists ? userSnap.data() : {};
  const usage = usageSnap.exists ? usageSnap.data() : {};
  const pkg = user.package || 'Free';
  const tier = PACKAGE_TIERS[pkg] || PACKAGE_TIERS.Free;

  const exp = user.packageExpiresAt?.toMillis?.() ?? user.packageExpiresAt ?? 0;
  const isExpired = pkg !== 'Free' && exp > 0 && exp < Date.now();

  const ordersUsed = usage.ordersUsed ?? 0;
  const isLimitReached = !tier.unlimited && ordersUsed >= tier.ordersTotal;

  return {
    pkg, tier, isExpired, ordersUsed, isLimitReached,
    usageRef: db.collection('usage').doc(uid),
    ordersLeft: tier.unlimited ? Infinity : Math.max(0, tier.ordersTotal - ordersUsed),
  };
}

