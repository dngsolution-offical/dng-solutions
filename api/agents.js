function checkAgentAccess(agentId, pkg) {
  const agent = AGENTS[agentId];
  if (!agent) return { ok: false, error: 'unknown_agent' };

  const userLevel = PACKAGE_LEVELS[pkg] ?? 0;
  const requiredLevel = PACKAGE_LEVELS[agent.minPackage] ?? 0;

  if (userLevel < requiredLevel) {
    return { ok: false, error: 'package_required', required: agent.minPackage, current: pkg };
  }
  return { ok: true, agent };
}

