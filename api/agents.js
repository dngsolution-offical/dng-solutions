async function checkRateLimit(uid, perMinute) {
  if (!db) return { ok: true, remaining: perMinute };
  const now = Date.now();
  const windowStart = now - 60000;
  const ref = db.collection('rate_limits').doc(uid);

  try {
    return await db.runTransaction(async (tx) => {
      const snap = await tx.get(ref);
      let stamps = (snap.exists && Array.isArray(snap.data().stamps)) ? snap.data().stamps : [];
      stamps = stamps.filter(t => t > windowStart);
      if (stamps.length >= perMinute) {
        return { ok: false, retryAfter: Math.ceil((stamps[0] + 60000 - now) / 1000) };
      }
      stamps.push(now);
      tx.set(ref, { stamps, updatedAt: admin.firestore.FieldValue.serverTimestamp() }, { merge: true });
      return { ok: true, remaining: perMinute - stamps.length };
    });
  } catch {
    return { ok: true, remaining: perMinute };
  }
}

