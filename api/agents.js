function calculateFinances(raw, priceList) {
  const { menus, programs } = priceList;
  const guests = Math.max(0, Number(raw.guests) || 0);
  const menuEntry = raw.menuKey ? menus[raw.menuKey] : null;
  const programEntry = raw.programKey ? programs[raw.programKey] : null;

  const menuTotal = menuEntry ? menuEntry.pricePerGuest * guests : 0;
  const programPrice = programEntry ? programEntry.price : 0;
  const extras = Array.isArray(raw.extras) ? raw.extras : [];
  const extrasTotal = extras.reduce((s, e) => s + (Number(e.price) || 0), 0);
  const subtotal = menuTotal + programPrice + extrasTotal;
  const taxAmount = Math.round(subtotal * TAX_RATE * 100) / 100;
  const totalAmount = Math.round((subtotal + taxAmount) * 100) / 100;
  const paidAmount = Math.max(0, Number(raw.paidAmount) || 0);
  const balance = Math.round((totalAmount - paidAmount) * 100) / 100;

  return {
    orderDate: raw.orderDate || null,
    clientName: raw.clientName || null,
    celebrantName: raw.celebrantName || null,
    guests,
    menuKey: raw.menuKey || null,
    menuSummary: menuEntry?.label || null,
    menuTotal: Math.round(menuTotal * 100) / 100,
    programKey: raw.programKey || null,
    programSummary: programEntry?.label || null,
    programPrice: Math.round(programPrice * 100) / 100,
    durationMinutes: programEntry?.duration ?? (Number(raw.durationMinutes) || null),
    extras,
    extrasTotal: Math.round(extrasTotal * 100) / 100,
    subtotal: Math.round(subtotal * 100) / 100,
    discount: 0,
    taxType: 'standard',
    taxRate: TAX_RATE,
    taxAmount,
    totalAmount,
    paidAmount,
    balance,
    status: raw.status || 'confirmed',
    confidence: typeof raw.confidence === 'number' ? raw.confidence : null,
    missingFields: Array.isArray(raw.missingFields) ? raw.missingFields : [],
  };
}

