// api/export-excel.js — Generate Excel file from order data
const { initializeFirebase } = require('./_firebase.cjs');
const ExcelJS = require('exceljs');

function buildExcelBuffer(orderData) {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = 'DNG Solutions';
  workbook.created = new Date();

  const sheet = workbook.addWorksheet('Order', {
    views: [{ showGridLines: true }],
  });

  // Column widths
  sheet.columns = [
    { header: 'Item', key: 'item', width: 30 },
    { header: 'Details', key: 'details', width: 20 },
    { header: 'Amount (₾)', key: 'amount', width: 15 },
  ];

  // Header styling
  const headerRow = sheet.getRow(1);
  headerRow.font = { bold: true, size: 12, color: { argb: 'FFFFFFFF' } };
  headerRow.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF2563EB' } };
  headerRow.alignment = { vertical: 'middle', horizontal: 'center' };
  headerRow.height = 28;

  // Order info section
  sheet.addRow([]);
  const infoStart = sheet.lastRow.number + 1;
  sheet.addRow(['ORDER DETAILS', '', '']);
  sheet.mergeCells(`A${infoStart}:C${infoStart}`);
  const infoHeader = sheet.getRow(infoStart);
  infoHeader.font = { bold: true, size: 14 };
  infoHeader.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF06B6D4' } };
  infoHeader.alignment = { horizontal: 'center' };
  infoHeader.height = 25;

  const addInfoRow = (label, value) => {
    const row = sheet.addRow([label, value || '—', '']);
    row.getCell(1).font = { bold: true };
    row.getCell(2).alignment = { wrapText: true };
  };

  addInfoRow('Client', orderData.clientName);
  addInfoRow('Celebrant', orderData.celebrantName);
  addInfoRow('Event Date', orderData.orderDate);
  addInfoRow('Guests', orderData.guests);
  addInfoRow('Status', orderData.status || 'pending');

  sheet.addRow([]);

  // Pricing table
  const priceStart = sheet.lastRow.number + 1;
  sheet.addRow(['PRICING', '', '']);
  sheet.mergeCells(`A${priceStart}:C${priceStart}`);
  const priceHeader = sheet.getRow(priceStart);
  priceHeader.font = { bold: true, size: 14 };
  priceHeader.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF06B6D4' } };
  priceHeader.alignment = { horizontal: 'center' };
  priceHeader.height = 25;

  // Menu
  if (orderData.menuSummary || orderData.menuTotal) {
    sheet.addRow([
      `Menu: ${orderData.menuSummary || orderData.menuKey || '—'}`,
      orderData.guests ? `${orderData.guests} guests` : '',
      Number(orderData.menuTotal) || 0,
    ]);
  }

  // Program
  if (orderData.programSummary || orderData.programPrice) {
    sheet.addRow([
      `Program: ${orderData.programSummary || orderData.programKey || '—'}`,
      orderData.durationMinutes ? `${orderData.durationMinutes} min` : '',
      Number(orderData.programPrice) || 0,
    ]);
  }

  // Extras
  if (Array.isArray(orderData.extras) && orderData.extras.length > 0) {
    orderData.extras.forEach(extra => {
      sheet.addRow([
        `Extra: ${extra.name || '—'}`,
        '',
        Number(extra.price) || 0,
      ]);
    });
  }

  // Subtotal
  sheet.addRow(['', '', '']);
  const subRow = sheet.addRow(['Subtotal', '', Number(orderData.subtotal) || 0]);
  subRow.font = { bold: true };

  // Tax
  if (orderData.taxAmount) {
    sheet.addRow([
      `Tax (${Math.round((orderData.taxRate || 0.18) * 100)}%)`,
      '',
      Number(orderData.taxAmount) || 0,
    ]);
  }

  // Total
  const totalRow = sheet.addRow(['TOTAL', '', Number(orderData.totalAmount) || 0]);
  totalRow.font = { bold: true, size: 14, color: { argb: 'FFFFFFFF' } };
  totalRow.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF2563EB' } };
  totalRow.height = 25;

  // Paid
  if (orderData.paidAmount) {
    sheet.addRow(['Paid', '', Number(orderData.paidAmount) || 0]);
  }

  // Balance
  if (orderData.balance) {
    const balRow = sheet.addRow(['Balance Due', '', Number(orderData.balance) || 0]);
    balRow.font = { bold: true, color: { argb: 'FFDC2626' } };
  }

  // Format amount column
  sheet.eachRow((row, rowNumber) => {
    if (rowNumber > 1) {
      const cell = row.getCell(3);
      if (typeof cell.value === 'number') {
        cell.numFmt = '#,##0.00" ₾"';
        cell.alignment = { horizontal: 'right' };
      }
    }
  });

  // Footer
  sheet.addRow([]);
  sheet.addRow([]);
  const footerRow = sheet.addRow(['Generated by DNG Solutions', new Date().toLocaleString(), '']);
  sheet.mergeCells(`A${footerRow.number}:C${footerRow.number}`);
  footerRow.font = { italic: true, size: 9, color: { argb: 'FF64748B' } };

  return workbook.xlsx.writeBuffer();
}

module.exports = async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');
  if (req.method === 'OPTIONS') return res.status(204).end();

  if (req.method !== 'POST') {
    return res.status(405).json({ ok: false, error: 'method_not_allowed' });
  }

  // ═══════ AUTH ═══════
  const authHeader = req.headers.authorization || '';
  if (!authHeader.startsWith('Bearer ')) {
    return res.status(401).json({ ok: false, error: 'no_token' });
  }

  let admin, auth;
  try {
    const init = initializeFirebase();
    admin = init.admin;
    auth = init.auth;
  } catch (e) {
    return res.status(500).json({ ok: false, error: 'firebase_init_failed', detail: e.message });
  }

  try {
    await auth.verifyIdToken(authHeader.slice(7));
  } catch (e) {
    return res.status(401).json({ ok: false, error: 'invalid_token', detail: e.message });
  }

  // ═══════ GET ORDER DATA ═══════
  const { order } = req.body || {};
  if (!order) {
    return res.status(400).json({ ok: false, error: 'missing_order_data' });
  }

  try {
    const buffer = await buildExcelBuffer(order);

    const filename = `order-${Date.now()}.xlsx`;
    res.setHeader('Content-Type', 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet');
    res.setHeader('Content-Disposition', `attachment; filename="${filename}"`);
    res.setHeader('Content-Length', buffer.length);

    return res.send(Buffer.from(buffer));
  } catch (e) {
    console.error('[export-excel]', e.message);
    return res.status(500).json({ ok: false, error: 'excel_generation_failed', detail: e.message });
  }
};