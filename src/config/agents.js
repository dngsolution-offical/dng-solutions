// ─── Helper functions ───

export function getUserPackageConfig(pkg) {
  return PACKAGE_CONFIG[pkg] || PACKAGE_CONFIG.Free;
}

export function canUseAgent(agentId, pkg) {
  const config = getUserPackageConfig(pkg);
  return config.allowedAgents.includes(agentId);
}

export function getAvailableAgents(pkg) {
  const config = getUserPackageConfig(pkg);
  return Object.values(AGENTS).filter(a => config.allowedAgents.includes(a.id));
}

export function getAgent(agentId) {
  return AGENTS[agentId] || null;
}

export function canUseTool(toolName, pkg) {
  const config = getUserPackageConfig(pkg);
  if (toolName === 'create_file') return config.allowFiles;
  if (toolName === 'create_excel') return config.allowExcel;
  return false;
}

export function getExcelLimits(pkg) {
  const config = getUserPackageConfig(pkg);
  return {
    maxRows: config.excelMaxRows,
    maxSheets: config.excelMaxSheets,
    allowed: config.allowExcel,
  };
}